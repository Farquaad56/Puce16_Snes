#!/usr/bin/env python3
"""Generate spc700 opcode tables from docs/specs/data/opcodes_spc700.tsv.

Usage:
    python gen_spc_tables.py          # generate table.rs
    python gen_spc_tables.py --check  # verify table.rs matches TSV (exit 1 on diff)
"""
import sys
import os

TSV_PATH = "docs/specs/data/opcodes_spc700.tsv"
OUT_PATH = "crates/puce16-core/src/apu/spc700/table.rs"


def read_tsv(path):
    """Read TSV, return list of (op_hex, mnemonic, bytes, cycles, branch_extra)."""
    rows = []
    with open(path, "r") as f:
        header = f.readline().strip()
        if not header.startswith("op\tmnemonic"):
            raise ValueError(f"Bad TSV header in {path}: {header!r}")
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split("\t")
            if len(parts) != 5:
                raise ValueError(f"Bad row (expected 5 cols): {line!r}")
            op_hex, mnemonic, b, c, be = parts
            rows.append((op_hex.strip(), mnemonic.strip(), int(b), int(c), int(be)))
    return rows


def validate_rows(rows):
    """Ensure exactly 256 unique opcodes."""
    if len(rows) != 256:
        raise ValueError(f"Expected 256 opcode rows, got {len(rows)}")
    ops = set()
    for op_hex, *_ in rows:
        val = int(op_hex, 16)
        if val < 0 or val > 255:
            raise ValueError(f"Opcode out of range: {op_hex}")
        if val in ops:
            raise ValueError(f"Duplicate opcode: {op_hex}")
        ops.add(val)


def generate_rs(rows):
    """Generate Rust table.rs content."""
    bytes_arr = [0] * 256
    cycles_arr = [0] * 256
    branch_arr = [0] * 256
    name_arr = ['""'] * 256

    for op_hex, mnemonic, b, c, be in rows:
        idx = int(op_hex, 16)
        bytes_arr[idx] = b
        cycles_arr[idx] = c
        branch_arr[idx] = be
        name_arr[idx] = f'"{mnemonic}"'

    lines = [
        "// GENERATED by docs/tools/gen_spc_tables.py - do not edit",
        "",
        "pub static BYTES: [u8; 256] = [" + ", ".join(str(x) for x in bytes_arr) + "];",
        "",
        "pub static CYCLES: [u8; 256] = [" + ", ".join(str(x) for x in cycles_arr) + "];",
        "",
        "pub static BRANCH_EXTRA: [u8; 256] = [" + ", ".join(str(x) for x in branch_arr) + "];",
        "",
    ]

    # NAME array on multiple lines for readability
    lines.append("pub static NAME: [&str; 256] = [")
    for i, name in enumerate(name_arr):
        if i > 0 and i % 8 == 0:
            lines[-1] += ","
            lines.append("")
        elif i > 0:
            lines[-1] += ", "
        lines[-1] += f"{name}"
    lines[-1] += "];"

    return "\n".join(lines) + "\n"


def main():
    check_only = "--check" in sys.argv

    rows = read_tsv(TSV_PATH)
    validate_rows(rows)

    generated = generate_rs(rows)

    if check_only:
        if not os.path.exists(OUT_PATH):
            print(f"--check: {OUT_PATH} does not exist")
            sys.exit(1)
        with open(OUT_PATH, "r") as f:
            existing = f.read()
        if existing == generated:
            print("--check: table.rs matches TSV")
            sys.exit(0)
        else:
            print("--check: table.rs differs from TSV (run without --check to regenerate)")
            sys.exit(1)

    with open(OUT_PATH, "w") as f:
        f.write(generated)
    print(f"Generated {OUT_PATH}")


if __name__ == "__main__":
    main()
