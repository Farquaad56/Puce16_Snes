#!/usr/bin/env python3
"""Generate crates/puce16-core/src/apu/dsp/gauss.rs from docs/specs/data/gauss_table.tsv."""

import sys
import os

TSV_PATH = "docs/specs/data/gauss_table.tsv"
OUT_PATH = "crates/puce16-core/src/apu/dsp/gauss.rs"


def read_tsv(path):
    """Read the TSV file and return list of (index, value) tuples."""
    rows = []
    with open(path, "r") as f:
        header = f.readline().strip()
        if not header.startswith("index"):
            raise ValueError(f"Bad header in {path}: {header}")
        for line in f:
            parts = line.strip().split("\t")
            if len(parts) != 2:
                raise ValueError(f"Bad row in {path}: {line.strip()}")
            idx, val = int(parts[0]), int(parts[1])
            rows.append((idx, val))
    return rows


def validate(rows):
    """Validate the table has exactly 512 consecutive indices."""
    if len(rows) != 512:
        raise ValueError(f"Expected 512 rows, got {len(rows)}")
    for i, (idx, val) in enumerate(rows):
        if idx != i:
            raise ValueError(f"Index mismatch at row {i}: expected {i}, got {idx}")
        if not (0 <= val <= 4095):
            raise ValueError(f"Value out of range at index {i}: {val}")


def generate_rust(rows):
    """Generate the Rust source code."""
    lines = [
        "// GENERATED by docs/tools/gen_gauss.py - do not edit",
        "",
        "pub static GAUSS: [i32; 512] = ["
    ]

    for i in range(0, len(rows), 16):
        chunk = rows[i:i+16]
        values = ", ".join(str(v) for _, v in chunk)
        lines.append(f"    {values},")

    lines[-1] = lines[-1].rstrip(",") + "];"
    return "\n".join(lines) + "\n"


def main():
    check_only = "--check" in sys.argv

    rows = read_tsv(TSV_PATH)
    validate(rows)

    rust_code = generate_rust(rows)

    if check_only:
        if os.path.exists(OUT_PATH):
            with open(OUT_PATH, "r") as f:
                existing = f.read()
            if existing == rust_code:
                print("OK: gauss.rs is up to date")
                sys.exit(0)
            else:
                print("FAIL: gauss.rs differs from generated content")
                sys.exit(1)
        else:
            print(f"FAIL: {OUT_PATH} does not exist")
            sys.exit(1)

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w") as f:
        f.write(rust_code)
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
