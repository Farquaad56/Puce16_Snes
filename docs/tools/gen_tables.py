#!/usr/bin/env python3
"""Generate cpu/table.rs from opcodes_65816.tsv.

Reads docs/specs/data/opcodes_65816.tsv and writes crates/puce16-core/src/cpu/table.rs
with Mn/Am enums and MN/AM lookup tables for all 256 opcodes.

Usage:
    python docs/tools/gen_tables.py          # generate table.rs
    python docs/tools/gen_tables.py --check  # verify table.rs is up to date (exit 1 if not)
"""

import sys
import os

TSV_PATH = "docs/specs/data/opcodes_65816.tsv"
OUT_PATH = "crates/puce16-core/src/cpu/table.rs"

# Addressing mode mapping: TSV mode string -> Rust Am variant
AM_MAP = {
    "imp": "Imp",
    "A": "Acc",
    "#": "Imm",
    "d": "Dp",
    "d,x": "DpX",
    "d,y": "DpY",
    "a": "Abs",
    "a,x": "AbsX",
    "a,y": "AbsY",
    "al": "Long",
    "al,x": "LongX",
    "(d)": "DpInd",
    "[d]": "DpIndLong",
    "(d,x)": "DpXInd",
    "(d),y": "DpIndY",
    "[d],y": "DpIndLongY",
    "d,s": "Sr",
    "(d,s),y": "SrIndY",
    "(a)": "AbsInd",
    "(a,x)": "AbsXInd",
    "[a]": "AbsIndLong",
    "rel": "Rel",
    "rell": "RelL",
    "blk": "Blk",
    "imm8": "Imm8",
    "pea": "Pea",
    "pei": "Pei",
    "per": "Per",
    "brk": "Brk",
    "cop": "Cop",
    "wdm": "Wdm",
}

# Am enum variant order (from spec)
AM_VARIANTS = [
    "Imp", "Acc", "Imm", "Dp", "DpX", "DpY", "Abs", "AbsX", "AbsY", "Long", "LongX",
    "DpInd", "DpIndLong", "DpXInd", "DpIndY", "DpIndLongY",
    "Sr", "SrIndY", "AbsInd", "AbsXInd", "AbsIndLong", "Rel", "RelL", "Blk", "Imm8",
    "Pea", "Pei", "Per", "Brk", "Cop", "Wdm",
]


def read_tsv(path):
    """Read opcodes TSV, return list of (op_hex, mnemonic, mode)."""
    rows = []
    with open(path, "r") as f:
        header = f.readline().strip()
        if not header.startswith("op\tmnemonic\tmode"):
            raise ValueError(f"Bad TSV header in {path}: {header!r}")
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split("\t")
            if len(parts) != 3:
                raise ValueError(f"Bad row in {path}: {line!r}")
            op_hex, mnemonic, mode = parts
            rows.append((op_hex, mnemonic, mode))
    return rows


def build_tables(rows):
    """Build Mn enum variants (sorted), AM lookup, and MN lookup."""
    # Collect unique mnemonics, sort alphabetically
    mnemonics = sorted(set(r[1] for r in rows))

    # Build opcode -> mnemonic index
    op_to_mn = {}
    for op_hex, mnemonic, _mode in rows:
        op_val = int(op_hex, 16)
        if op_val in op_to_mn:
            raise ValueError(f"Duplicate opcode {op_hex}")
        op_to_mn[op_val] = mnemonic

    # Build opcode -> Am variant index
    op_to_am = {}
    for op_hex, _mnemonic, mode in rows:
        op_val = int(op_hex, 16)
        if mode not in AM_MAP:
            raise ValueError(f"Unknown addressing mode {mode!r} at opcode {op_hex}")
        op_to_am[op_val] = AM_MAP[mode]

    # Verify all Am variants are used (should be exactly 31)
    used_ams = set(op_to_am.values())
    expected_ams = set(AM_VARIANTS)
    if used_ams != expected_ams:
        missing = expected_ams - used_ams
        extra = used_ams - expected_ams
        raise ValueError(f"Am variant mismatch. Missing: {missing}, Extra: {extra}")

    return mnemonics, op_to_mn, op_to_am


def generate_rust(mnemonics, op_to_mn, op_to_am):
    """Generate the Rust table.rs content."""
    lines = []
    lines.append("// GENERATED by docs/tools/gen_tables.py - do not edit")
    lines.append("")

    # Mn enum (alphabetical)
    lines.append("#[derive(Clone, Copy, PartialEq, Eq, Debug)]")
    lines.append("pub enum Mn { " + ", ".join(mnemonics) + " }")
    lines.append("")

    # Am enum (spec order)
    lines.append("#[derive(Clone, Copy, PartialEq, Eq, Debug)]")
    lines.append("pub enum Am { " + ", ".join(AM_VARIANTS) + " }")
    lines.append("")

    # MN lookup table [Mn; 256]
    lines.append("pub static MN: [Mn; 256] = [")
    for i in range(0, 256, 8):
        row_parts = []
        for j in range(i, min(i + 8, 256)):
            mn = op_to_mn[j]
            row_parts.append(f"Mn::{mn}")
        lines.append("    " + ", ".join(row_parts) + ",")
    lines.append("];")
    lines.append("")

    # AM lookup table [Am; 256]
    lines.append("pub static AM: [Am; 256] = [")
    for i in range(0, 256, 8):
        row_parts = []
        for j in range(i, min(i + 8, 256)):
            am = op_to_am[j]
            row_parts.append(f"Am::{am}")
        lines.append("    " + ", ".join(row_parts) + ",")
    lines.append("];")
    lines.append("")

    # Mn::name() impl
    lines.append("impl Mn {")
    lines.append("    pub fn name(self) -> &'static str {")
    lines.append("        match self {")
    for mn in mnemonics:
        lines.append(f"            Mn::{mn} => \"{mn}\",")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")

    return "\n".join(lines) + "\n"


def main():
    check_mode = "--check" in sys.argv

    if not os.path.exists(TSV_PATH):
        print(f"Error: TSV file not found: {TSV_PATH}", file=sys.stderr)
        sys.exit(1)

    rows = read_tsv(TSV_PATH)
    mnemonics, op_to_mn, op_to_am = build_tables(rows)
    generated = generate_rust(mnemonics, op_to_mn, op_to_am)

    if check_mode:
        if not os.path.exists(OUT_PATH):
            print(f"Error: {OUT_PATH} does not exist", file=sys.stderr)
            sys.exit(1)
        with open(OUT_PATH, "r") as f:
            existing = f.read()
        if existing == generated:
            print("OK: table.rs is up to date")
            sys.exit(0)
        else:
            print(f"Error: {OUT_PATH} differs from generated output", file=sys.stderr)
            # Show first difference location for debugging
            for i, (a, b) in enumerate(zip(existing.splitlines(), generated.splitlines())):
                if a != b:
                    print(f"  First diff at line {i+1}", file=sys.stderr)
                    break
            sys.exit(1)
    else:
        with open(OUT_PATH, "w") as f:
            f.write(generated)
        print(f"Generated {OUT_PATH}")


if __name__ == "__main__":
    main()
