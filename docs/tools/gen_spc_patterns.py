#!/usr/bin/env python3
"""Generate the SPC700 bus cycle pattern table from the SingleStepTests oracle.

Usage:
    python docs/tools/gen_spc_patterns.py          # write crates/puce16-core/src/apu/spc700/pattern.rs
    python docs/tools/gen_spc_patterns.py --check  # verify the committed file matches the oracle (exit 1 on diff)

Pattern characters: R = bus read, W = bus write, . = internal (wait) cycle.
The base pattern is the NOT TAKEN one; a taken branch appends BRANCH_EXTRA internal cycles.
Needs tests/oracle/spc700/v1/*.json (not committed) and docs/specs/data/opcodes_spc700.tsv.
"""
import glob
import json
import os
import sys

ORACLE = "tests/oracle/spc700/v1/*.json"
TSV = "docs/specs/data/opcodes_spc700.tsv"
OUT = "crates/puce16-core/src/apu/spc700/pattern.rs"
KIND = {"read": "R", "write": "W", "wait": "."}


def read_tsv():
    rows = {}
    with open(TSV) as f:
        f.readline()
        for line in f:
            if line.strip():
                op, _name, _b, cyc, extra = line.rstrip("\n").split("\t")[:5]
                rows[int(op, 16)] = (int(cyc), int(extra))
    return rows


def build():
    tsv = read_tsv()
    patterns = {}
    for path in sorted(glob.glob(ORACLE)):
        op = int(os.path.basename(path).split(".")[0], 16)
        seen = set()
        for case in json.load(open(path)):
            seen.add("".join(KIND[k] for _a, _v, k in case["cycles"]))
        base = min(seen, key=len)
        cyc, extra = tsv[op]
        for p in seen:
            if p != base and p != base + "." * extra:
                raise SystemExit("%02X: unexpected pattern %r (base %r, extra %d)" % (op, p, base, extra))
        if len(base) != cyc:
            raise SystemExit("%02X: pattern length %d != TSV cycles %d (base %r)" % (op, len(base), cyc, base))
        if not base.startswith("R"):
            raise SystemExit("%02X: pattern must start with the opcode fetch: %r" % (op, base))
        patterns[op] = base
    if len(patterns) != 256:
        raise SystemExit("expected 256 opcodes, got %d" % len(patterns))
    lines = ["// GENERATED by docs/tools/gen_spc_patterns.py from tests/oracle/spc700 - do not edit", "",
             "/// Bus cycle kinds per opcode (not taken): R read, W write, . internal cycle.",
             "pub static PATTERN: [&str; 256] = ["]
    for op in range(256):
        lines.append('    "%s", // %02X' % (patterns[op], op))
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, newline="").read().replace("\r\n", "\n")
        if cur != text:
            print("pattern.rs differs from the oracle")
            return 1
        print("pattern.rs OK")
        return 0
    with open(OUT, "w", newline="\n") as f:
        f.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())