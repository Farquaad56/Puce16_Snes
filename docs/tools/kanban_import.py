#!/usr/bin/env python
"""kanban_import.py - create the Puce16 tasks in the Nous Hermes Kanban (docs/03_KANBAN_HERMES.md).

    python docs/tools/kanban_import.py --dry-run                 # print the commands, run nothing
    python docs/tools/kanban_import.py                            # import everything (non-deferred)
    python docs/tools/kanban_import.py --only E01                 # one epic
    python docs/tools/kanban_import.py --from E02-05 --to E02-20  # a range (parents come from id_map.json)
    python docs/tools/kanban_import.py --limit 10                 # the next 10 tasks not imported yet

Reads docs/kanban/tasks.json (generated by build_tasks.py) and writes docs/kanban/id_map.json (task id -> Kanban id)
after EACH creation, so an interrupted import resumes where it stopped.  Every card carries the idempotency key
puce16-<ID>: running the script twice never creates duplicates.

D-020: the tasks form ONE chain (each task has the previous one as parent) -> one task at a time.
GATE tasks are created WITHOUT assignee (human validation).  Deferred tasks (E09) are skipped unless --include-deferred.
Python 3.8+, standard library only.
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TASKS = ROOT / "docs" / "kanban" / "tasks.json"
IDMAP = ROOT / "docs" / "kanban" / "id_map.json"

POINTER = """# {id} - {title}

La specification COMPLETE de cette tache est dans le fichier `docs/tasks/{id}.md` du depot (ton workspace).
LIS CE FICHIER EN ENTIER AVANT DE CODER (Write only in, Specification, Tests, Acceptance) : il fait foi.
"""


def die(msg):
    print("ERROR: " + msg)
    sys.exit(2)


def shorten(args):
    out = []
    for a in args:
        if len(a) > 80:
            a = a[:60].replace("\n", " ") + "... (%d chars)" % len(a)
        out.append('"%s"' % a if (" " in a or not a) else a)
    return " ".join(out)


def extract_id(stdout):
    s = stdout.strip()
    try:
        data = json.loads(s)
        if isinstance(data, dict):
            for k in ("id", "task_id"):
                if k in data and data[k]:
                    return str(data[k])
            for v in data.values():
                if isinstance(v, dict):
                    for k in ("id", "task_id"):
                        if k in v and v[k]:
                            return str(v[k])
    except ValueError:
        pass
    m = re.search(r"\bt_[0-9a-zA-Z]+\b", s)
    return m.group(0) if m else None


def small_body(t, max_body):
    body = t["body"]
    if max_body and len(body) > max_body:
        footer = body[body.rfind("\n---\n## Regles permanentes"):] if "\n---\n## Regles permanentes" in body else ""
        body = POINTER.format(id=t["id"], title=t["title"].split(" ", 1)[-1]) + footer
    return body


def main():
    ap = argparse.ArgumentParser(description="Import the Puce16 tasks into the Hermes Kanban")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--only", help="epic (E03) or task id prefix")
    ap.add_argument("--from", dest="from_id")
    ap.add_argument("--to", dest="to_id")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--assignee", default="Puce16_Snes")
    ap.add_argument("--board", default="puce16")
    ap.add_argument("--workspace", default="H:/__Emulator__/Puce16_Snes")
    ap.add_argument("--hermes", default="hermes")
    ap.add_argument("--max-body", type=int, default=7500,
                    help="cards longer than this get a short body pointing to docs/tasks/<ID>.md (0 = never; "
                         "needed if the hermes launcher is a .cmd file: Windows limits it to 8191 characters)")
    ap.add_argument("--include-deferred", action="store_true")
    a = ap.parse_args()

    data = json.loads(TASKS.read_text(encoding="utf-8"))
    tasks = data["tasks"]
    ids = [t["id"] for t in tasks]
    idmap = json.loads(IDMAP.read_text(encoding="utf-8")) if IDMAP.exists() else {}
    tenant = data.get("tenant", "puce16")

    def keep(t):
        if t["role"] == "none" and not a.include_deferred:
            return False
        if a.only and not t["id"].startswith(a.only.upper()):
            return False
        if a.from_id and ids.index(t["id"]) < ids.index(a.from_id.upper()):
            return False
        if a.to_id and ids.index(t["id"]) > ids.index(a.to_id.upper()):
            return False
        return True

    todo = [t for t in tasks if keep(t) and (a.dry_run or t["id"] not in idmap)]
    if a.limit:
        todo = todo[:a.limit]
    if not todo:
        print("nothing to import")
        return 0

    exe = a.hermes
    if not a.dry_run:
        if shutil.which(exe) is None:
            die("'%s' not found in PATH (use --hermes <path>)" % exe)

    created = 0
    for t in todo:
        tid = t["id"]
        args = [exe, "kanban", "--board", a.board, "create", t["title"], "--body", small_body(t, a.max_body)]
        if t["role"] not in ("user", "claude", "none") and not t["gate"]:
            args += ["--assignee", a.assignee]
        for p in t["parents"]:
            pk = idmap.get(p)
            if pk is None and not a.dry_run:
                die("parent %s of %s is not in id_map.json: import the earlier tasks first (or omit --only/--from)" % (p, tid))
            args += ["--parent", pk if pk else "<%s>" % p]
        args += ["--tenant", tenant, "--workspace", "dir:" + a.workspace.replace("\\", "/"),
                 "--priority", str(t["priority"]), "--idempotency-key", t["idempotency_key"],
                 "--max-runtime", t["max_runtime"], "--max-retries", str(t["max_retries"])]
        if t["role"] == "none":
            args.append("--triage")
        args.append("--json")
        if a.dry_run:
            print(shorten(args))
            continue
        r = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)
        if r.returncode != 0:
            print("FAILED: " + shorten(args))
            print(r.stdout)
            print(r.stderr)
            die("stopped at %s (the ones before are in id_map.json; fix and rerun)" % tid)
        kid = extract_id(r.stdout)
        if not kid:
            print(r.stdout)
            die("cannot read the Kanban id from the output of 'create' for %s (see docs/03_KANBAN_HERMES.md section 6)" % tid)
        idmap[tid] = kid
        IDMAP.write_text(json.dumps(idmap, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
        created += 1
        print("%s -> %s%s" % (tid, kid, "  (GATE, no assignee)" if t["gate"] else ""))
    if not a.dry_run:
        print("%d task(s) created/confirmed; id map: docs/kanban/id_map.json" % created)
    return 0


if __name__ == "__main__":
    sys.exit(main())
